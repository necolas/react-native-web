/**
 * Creates a map of exported modules, allowing the RNW babel plugin to rewrite
 * paths only for modules it knows are exported by RNW.
 *
 * By default, exits with an error if the file is not up to date.
 * With --write, updates the file.
 */
import fs from 'node:fs';
import path from 'node:path';

const isDirectory = (source) => fs.lstatSync(source).isDirectory();

const getDirectories = (source) =>
  fs.readdirSync(source).filter((name) => isDirectory(path.join(source, name)));

const packagesDir = path.join(import.meta.dirname, '../packages/');
const exportsDir = path.join(packagesDir, 'react-native-web/src/exports');
const identifierRegex = /^[A-Za-z_$][\w$]*$/;

const moduleMapOutfile = path.join(
  packagesDir,
  'babel-plugin-react-native-web/src/moduleMap.js'
);

const moduleMapEntries = getDirectories(exportsDir)
  .map((name) => {
    return `  ${
      identifierRegex.test(name) ? name : `'${name.replace(/[\\']/g, '\\$&')}'`
    }: true`;
  })
  .join(',\n');

const moduleMapData = `// THIS FILE IS AUTOMATICALLY GENERATED. DO NOT EDIT.
module.exports = {
${moduleMapEntries}
};
`;

if (process.argv.includes('--write')) {
  fs.writeFileSync(moduleMapOutfile, moduleMapData);
} else if (
  !fs.existsSync(moduleMapOutfile) ||
  fs.readFileSync(moduleMapOutfile, 'utf-8') !== moduleMapData
) {
  console.error(
    `${path.relative(process.cwd(), moduleMapOutfile)} is not up to date.`
  );

  console.error('Run `npm run module-map` and stage the changes.');
  process.exit(1);
}
